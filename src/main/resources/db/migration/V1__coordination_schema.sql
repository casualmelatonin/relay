CREATE TABLE agent_profiles (
    id UUID PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    normalized_name VARCHAR(160) NOT NULL UNIQUE,
    role VARCHAR(160) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    color VARCHAR(7) NOT NULL,
    last_seen TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_agents_subject ON agent_profiles (subject);

CREATE TABLE work_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    title VARCHAR(240) NOT NULL,
    item_type VARCHAR(20) NOT NULL,
    parent_id BIGINT REFERENCES work_items(id),
    status VARCHAR(20) NOT NULL,
    priority VARCHAR(20) NOT NULL,
    assignee_id UUID REFERENCES agent_profiles(id),
    claimant_id UUID REFERENCES agent_profiles(id),
    claim_token UUID,
    lease_until TIMESTAMP WITH TIME ZONE,
    description VARCHAR(8000) NOT NULL,
    acceptance VARCHAR(8000) NOT NULL,
    output VARCHAR(8000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_item_type CHECK (item_type IN ('INITIATIVE', 'EPIC', 'STORY', 'TASK')),
    CONSTRAINT ck_work_status CHECK (status IN ('BACKLOG', 'READY', 'IN_PROGRESS', 'REVIEW', 'DONE', 'BLOCKED')),
    CONSTRAINT ck_priority CHECK (priority IN ('URGENT', 'HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_claim_complete CHECK (
        (claimant_id IS NULL AND claim_token IS NULL AND lease_until IS NULL)
        OR (claimant_id IS NOT NULL AND claim_token IS NOT NULL AND lease_until IS NOT NULL)
    )
);
CREATE INDEX ix_work_items_parent ON work_items (parent_id);
CREATE INDEX ix_work_items_assignee ON work_items (assignee_id);
CREATE INDEX ix_work_items_status ON work_items (status);
CREATE INDEX ix_work_items_claimant ON work_items (claimant_id, lease_until);

CREATE TABLE work_item_labels (
    work_item_id BIGINT NOT NULL REFERENCES work_items(id) ON DELETE CASCADE,
    label VARCHAR(100) NOT NULL,
    PRIMARY KEY (work_item_id, label)
);

CREATE TABLE work_item_dependencies (
    work_item_id BIGINT NOT NULL REFERENCES work_items(id) ON DELETE CASCADE,
    prerequisite_id BIGINT NOT NULL REFERENCES work_items(id),
    PRIMARY KEY (work_item_id, prerequisite_id),
    CONSTRAINT ck_dependency_not_self CHECK (work_item_id <> prerequisite_id)
);
CREATE INDEX ix_prerequisite ON work_item_dependencies (prerequisite_id);

CREATE TABLE activity_events (
    id UUID PRIMARY KEY,
    item_id BIGINT REFERENCES work_items(id),
    actor VARCHAR(200) NOT NULL,
    message VARCHAR(8000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_activity_created ON activity_events (created_at, id);
CREATE INDEX ix_activity_item_created ON activity_events (item_id, created_at);
